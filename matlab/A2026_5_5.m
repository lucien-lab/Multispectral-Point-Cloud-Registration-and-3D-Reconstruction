%% ===================== 辅助函数 =====================
% -------------------------------------------------------------------------
% 滑动平均滤波器
% -------------------------------------------------------------------------
% 输入: input - 输入信号, window_size - 窗口大小
% 输出: output - 滤波后信号
%
% 原理: 输出每个点是输入窗口内所有点的平均值
% 实现: 使用卷积, 窗口内系数均为1/window_size
% 'same' 参数保证输出与输入长度相同
function output = moving_average_filter(input, window_size)
    output = conv(input, ones(1, window_size) / window_size, 'same');
end
