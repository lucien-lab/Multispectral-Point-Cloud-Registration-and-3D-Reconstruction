%% ========================================================================
%% 2026_5_5: 超光谱激光雷达数据处理 - 整合管线
%% 输出: (x, y, z, 光谱6维度) + 灰度点云 + 彩色点云
%% ========================================================================
% 功能说明:
%   本脚本将A1-A3共5个处理阶段整合为单一管线，从原始ADC二进制数据出发，
%   最终输出3D点云坐标、6个光谱通道的反射率、以及灰度/彩色可视化点云图片。
%
% 数据流程:
%   left.bin (ADC原始) -> 步骤1: DataMatrix
%                       -> 步骤2: Range + Echo_cal + Data_X_1stEchosPeak
%                       -> 步骤3: xp/yp/zp (3D坐标)
%                       -> 步骤4: RFL (6通道反射率)
%                       -> 步骤5: clb (RGB颜色) + 点云图片
%
% 输出文件:
%   - Output_Data_2026_5_5.mat : [x,y,z,RFL_495,RFL_545,RFL_600,RFL_642,RFL_696,RFL_803] 合并矩阵
%   - XYZ_Results_2026_5_5.mat : 3D坐标 (3 x 9000)
%   - RFL_2026_5_5.mat         : 6通道反射率 (9000 x 6)
%   - PointCloud_Grayscale_*.png : 灰度点云 (按距离上色)
%   - PointCloud_Color_*.png    : 彩色点云 (按光谱上色)
%   - Spectral_Reflectance_*.png : 6波长反射率波形

clc; clear; close all;

%% ===================== 1. 全局参数 =====================
% ========================================================================
% 硬件参数 - 描述ADC采集系统的基本配置
% ========================================================================

sample_length = 13312;    % 每次触发采集的ADC采样点总数
                          % 每个采样点代表0.096ns (1/10.4GHz)
                          % 总采集窗口: 13312 * 0.096ns ≈ 1280ns

sample_num = 9000;        % 总扫描次数/线数 (Scanner sweeps)
                          % 对应扫描仪转一圈采集的点数

SamFreq = 10.4;          % ADC采样频率, 单位GHz
                          % 采样周期 = 1/10.4GHz ≈ 0.096ns
                          % 也用于计算TOF: TOF = 峰值位置 / SamFreq

level_mainwave = 100;     % 主波检测阈值 (ADC量化值)
                          % 用于判断主波信号的上升沿位置
                          % 主波是发射激光的同步参考脉冲

max_range = 28;         % 激光雷达最大探测距离, 单位m
                          % 用于计算最大飞行时间(TOF)

zslv = 1;                % 折射率 ( refractive index of medium )
                          % 空气折射率约为1
                          % 若在水中测量需修改此值

% ========================================================================
% 飞行时间参数 - 根据最大探测距离计算有效信号长度
% ========================================================================

% 最大飞行时间 TOF (Time of Flight)
%   公式推导:
%     距离 = 速度 × 时间/2 (往返)
%     max_range = c × max_tof / (2 × zslv)
%     其中 c = 3e8 m/s = 3e10 cm/s = 3e10/10.4 个采样点/ns (换算)
%     简化后: max_tof = zslv × max_range × 100 / 15  (ns)
%   物理含义: 激光从发射到最远目标返回的时间
max_tof = zslv * max_range * 100 / 15;  % ns, 最大飞行时间

len_echopulse = 800;      % 回波脉冲长度, 单位采样点
                          % 预留的回波信号空间, 确保完整脉冲在窗口内

% 有效信号长度 = 采样频率 × 最大TOF + 回波脉冲长度
%   SamFreq × max_tof = 10.4 × (28×100/15) ≈ 1949 采样点
%   加上回波脉冲长度800, 确保信号不截断
sample_length_valid = round(SamFreq * max_tof + len_echopulse);  % 采样点

len_mainwavepulse = 61;   % 主波脉冲长度, 单位采样点 (参考值)

% ========================================================================
% 6通道脉冲模板参数 - 用于互相关检测
% ========================================================================

% SWB = Six-Wavelength Beacon, 6波长脉冲模板
% 这是6个标准脉冲在采样序列中的参考位置 (单位: 采样点)
% 来自激光器发出的6个不同波长脉冲的固定延时模式
X_peaks_SWB = [932, 1078, 1183, 1339, 1521, 1726];

% 模板相对偏移量 (以932为基准0点)
%   用于构建互相关检测的模板信号
X_peaks_temp = X_peaks_SWB - 931;  % [1, 147, 252, 408, 590, 795]

% 6波长对应的基准脉冲幅度 (ADC量化值)
%   这是标定板(白板)反射的参考脉冲幅度
%   各波长由于光源功率、探测器灵敏度不同, 幅度不同
% 旧白板参考幅值（保留备查）
% Y_Amp_SWB = [1.241064096774194e+02, 1.202428838709678e+02, 1.150127903225807e+02, ...
%              1.663828838709677e+02, 1.158136612903226e+02, 2.266485516129032e+02];

% 当前使用的白板参考幅值
Y_Amp_SWB = [531.2975, 396.4109, 425.0606, ...
             361.2250, 572.4702, 477.3115];
% 对应波长: 495nm, 696nm, 600nm, 803nm, 545nm, 642nm

% ========================================================================
% 光谱参数
% ========================================================================

% 6个光谱通道的中心波长, 单位nm
% 注意: 波长顺序与通道对应 [495nm, 696nm, 600nm, 803nm, 545nm, 642nm]
lam6da = [495, 696, 600, 803, 545, 642];

%% ===================== 2. 步骤1: 读取ADC原始数据 =====================
% ========================================================================
% 功能: 从二进制文件读取原始ADC采样数据
% 输入: left.bin - int16格式的二进制原始数据
% 输出: DataMatrix - 9000 x 13312 的二维矩阵
%
% 数据排布: 每个scan包含13312个int16采样值, 共9000个scan连续存储
% ========================================================================

fprintf('\n--- 步骤1: 读取ADC原始数据 ---\n');

% 数据文件路径定义
bin_path = 'D:\Lucien\workspace\3D\3_28\20260328\left.bin';      % ADC原始二进制数据
angle_path = 'D:\Lucien\workspace\3D\3_28\angle\left.txt';       % 角度编码器数据 (16进制ASCII)
cmf_path = 'D:\Lucien\workspace\3D\3_28\cmf-461-700nm.mat';     % CIE色彩匹配函数

% 检查数据文件是否存在
if ~exist(bin_path, 'file')
    error('找不到数据文件: %s', bin_path);
end

% 打开二进制文件进行读取
%   'rb' = read binary
fid = fopen(bin_path, 'rb');

% 读取所有int16数据
% fread默认按列排布, 结果是13312*9000 = 119,808,000个int16值
data = fread(fid, 'int16');

% 关闭文件
fclose(fid);

% ========================================================================
% 重塑数据为矩阵形式
% 每行代表一次扫描 (scan), 每列代表一个采样点
% ========================================================================

% 初始化矩阵: 9000行(扫描) x 13312列(采样点)
DataMatrix = zeros(sample_num, sample_length);

% 按scan顺序重排数据
% 每个scan占13312个采样点, 按行排布
for i = 1:sample_num
    % 第i行 = 第(i-1)*13312+1 到 第i*13312 个元素, 转置为行向量
    DataMatrix(i, :) = data((i - 1) * sample_length + 1 : i * sample_length)';
end

fprintf('ADC数据读取完成: %d x %d\n', size(DataMatrix));

%% ===================== 3. 步骤2: 回波处理与距离计算 =====================
% ========================================================================
% 功能:
%   (1) 对每个scan检测主波上升沿, 截取有效回波信号
%   (2) 5点滑动平均滤波去噪
%   (3) 互相关法检测6个波长的回波峰值位置
%   (4) 根据TOF计算目标距离
%
% 核心原理 - 互相关检测:
%   将6脉冲模板信号与回波信号做互相关, 相关峰值位置即为回波TOF
%   互相关可以有效抑制噪声, 提高峰值检测精度
%
% 距离计算:
%   TOF (ns) = 峰值位置 / SamFreq
%   Range (m) = 0.15 * TOF / zslv
%   (系数0.15 = 光速c/2 换算而来: c/2 = 3e8/2 = 1.5e8 m/s = 0.15 m/ns)
% ========================================================================

fprintf('\n--- 步骤2: 回波处理与距离计算 ---\n');

% 预分配内存
Echo_cal = zeros(sample_num, sample_length_valid);           % 滤波后回波信号
Data_X_1stEchosPeak = zeros(1, sample_num);                 % 互相关峰值位置
Range = zeros(1, sample_num);                              % 距离值 (m)

% 主循环: 逐个scan处理
for j = 1:sample_num
    % -------------------------------------------------------------------------
    % 3.1 提取原始信号的一行 (第j次扫描)
    % -------------------------------------------------------------------------
    signal_raw = DataMatrix(j, :);  % 1 x 13312 行向量

    % -------------------------------------------------------------------------
    % 3.2 主波上升沿检测
    % -------------------------------------------------------------------------
    % 主波是激光发射的同步参考脉冲, 幅度远高于回波
    % 从信号末尾向前搜索, 找到第一个超过阈值的点 (上升沿)
    for nn = 0:length(signal_raw) - 1
        if signal_raw(length(signal_raw) - nn) > level_mainwave
            mainwave_risingedge = length(signal_raw) - nn;
            break;
        end
    end

    % -------------------------------------------------------------------------
    % 3.3 定位主波峰值, 计算有效信号起始点
    % -------------------------------------------------------------------------
    % 在主波上升沿附近截取一个脉冲窗口 (30个采样点)
    mainwave_pulse = signal_raw(mainwave_risingedge - 12 : mainwave_risingedge + 17);

    % 找到脉冲峰值
    mainwave_max = max(mainwave_pulse);
    mainwave_max_indices = find(mainwave_pulse == mainwave_max);

    % 计算有效信号起始位置
    % 峰值位置 - 50 = 估计的发射时刻 (相对于有效窗口起点的偏移)
    mainwave_start = mainwave_risingedge + mainwave_max_indices - 50;

    % -------------------------------------------------------------------------
    % 3.4 截取有效回波信号
    % -------------------------------------------------------------------------
    % 从发射时刻开始, 截取sample_length_valid个采样点
    % 这个窗口包含了激光往返的所有回波信号
    signal_v = signal_raw(mainwave_start : mainwave_start + sample_length_valid - 1);

    % -------------------------------------------------------------------------
    % 3.5 滑动平均滤波
    % -------------------------------------------------------------------------
    % 5点滑动平均, 等效于低通滤波器, 抑制高频噪声
    signal_cal = moving_average_filter(signal_v, 5);
    Echo_cal(j, :) = signal_cal;

    % -------------------------------------------------------------------------
    % 3.6 互相关检测回波峰值 (核心算法)
    % -------------------------------------------------------------------------
    % 构建6脉冲模板信号
    % 在与X_peaks_temp对应位置置1, 其余为0
    signal_temp = zeros(1, length(signal_cal));
    signal_temp(X_peaks_temp) = 1;  % 模板: [1,0,...,0,1,0,...,1,...]

    % 前300点置零 (去除主波附近干扰)
    signal_det = signal_cal;
    signal_det(1:300) = 0;

    % 计算互相关
    % xcorr(a,b) = a与b的互相关, 结果长度 = len(a) + len(b) - 1
    corr_det = xcorr(signal_det, signal_temp);

    % 取后半部分 (与模板等长的结果)
    corr_det = corr_det(length(signal_temp):end);

    % 找相关峰值位置 -> 即为回波到达时刻
    [~, max_idx] = max(corr_det);
    Data_X_1stEchosPeak(j) = max_idx;

    % -------------------------------------------------------------------------
    % 3.7 计算距离
    % -------------------------------------------------------------------------
    % TOF (ns) = 峰值索引 / 采样频率
    %   峰值索引代表采样点序号, 除以10.4GHz得时间(ns)
    % Range (m) = 0.15 × TOF / 折射率
    %   0.15 = c/2 = 光速一半 (m/ns), 往返需除以2
    TOF = max_idx / SamFreq;           % 飞行时间, ns
    Range(j) = 0.15 * TOF / zslv;      % 距离, m

    % 每1000个scan报告进度
    if mod(j, 1000) == 0
        fprintf('  已处理 %d / %d\n', j, sample_num);
    end
end

fprintf('距离计算完成: Range范围 [%.2f, %.2f] m\n', min(Range), max(Range));

%% ===================== 4. 步骤3: 角度计算与3D坐标 =====================
% ========================================================================
% 功能:
%   (1) 读取角度编码器数据 (16进制格式)
%   (2) 解析水平角(Ag_X)和俯仰角(Ag_Y)
%   (3) 将极坐标(Range, Ag_X, Ag_Y)转换为笛卡尔坐标(x, y, z)
%
% 角度编码器协议:
%   每6字节表示一组角度数据: [ID_high, ID_low, X_high, X_low, Y_high, Y_low]
%   Ag_X = 256*X_high + X_low
%   Ag_Y = 256*Y_high + Y_low
%
% 坐标变换 (扫描仪安装角度修正):
%   Ag_X = kx × 2π × (Ag_X_tt - 19650) / 40000   (水平角度, rad)
%   Ag_Y = 2π × (36500 - Ag_Y_tt) / 1200000     (俯仰角度, rad)
%
% 3D坐标计算:
%   dl = 1000 × Range × cos(Ag_Y)  (水平距离, mm)
%   xp = dl × cos(Ag_X)            (X坐标, mm)
%   yp = -dl × sin(Ag_X)          (Y坐标, mm, 负号修正方向)
%   zp = 1000 × Range × sin(Ag_Y) + 1900  (Z坐标, mm, 加1900为高度修正)
% ========================================================================

fprintf('\n--- 步骤3: 角度计算与3D坐标 ---\n');

% -------------------------------------------------------------------------
% 4.1 读取角度数据
% -------------------------------------------------------------------------
% 角度文件为ASCII文本, 每两个字符表示一个16进制字节
fid = fopen(angle_path, 'r');

% '%x' 格式符读取16进制数, 结果为数值数组
hexData = fscanf(fid, '%x')';
fclose(fid);

% -------------------------------------------------------------------------
% 4.2 解析角度编码
% -------------------------------------------------------------------------
% 计算角度数据组数 (每组6字节)
Num_Ag = floor(length(hexData) / 6);

% 初始化角度数组
Ag_X_raw = zeros(1, Num_Ag);  % 水平角原始值
Ag_Y_raw = zeros(1, Num_Ag);  % 俯仰角原始值

% 逐组解析6字节角度数据
for i = 1:Num_Ag
    % 每组6字节: [ID_high, ID_low, X_high, X_low, Y_high, Y_low]
    Ag_X_raw(i) = 256 * hexData((i - 1) * 6 + 4) + hexData((i - 1) * 6 + 3);
    Ag_Y_raw(i) = 256 * hexData((i - 1) * 6 + 6) + hexData((i - 1) * 6 + 5);
end

% -------------------------------------------------------------------------
% 4.3 取前sample_num个角度 (与Range对应)
% -------------------------------------------------------------------------
Ag_X_tt = Ag_X_raw(1:sample_num);
Ag_Y_tt = Ag_Y_raw(1:sample_num);

% -------------------------------------------------------------------------
% 4.4 坐标变换
% -------------------------------------------------------------------------
% 水平角度变换 (修正编码器偏置和非线性)
%   19650是编码器零点偏移, 40000是编码器分辨率
kx = 1.25;  % 修正系数 (用于校正角度刻度)
Ag_X = kx * 2 * pi * (Ag_X_tt - 19650) / 40000;  % rad

% 俯仰角度变换
%   36500是编码器零点, 1200000是分辨率
Ag_Y = 2 * pi * (36500 - Ag_Y_tt) / 1200000;  % rad

% -------------------------------------------------------------------------
% 4.5 极坐标转笛卡尔坐标
% -------------------------------------------------------------------------
% 水平距离 = Range × cos(俯仰角), 转换为mm
dl = 1000 * Range .* cos(Ag_Y);

% 3D坐标计算
zp = 1000 * Range .* sin(Ag_Y) + 1900;   % Z: 俯仰分量 + 高度偏移1900mm
xp = dl .* cos(Ag_X);                     % X: 水平距离 × cos(水平角)
yp = -dl .* sin(Ag_X);                    % Y: 水平距离 × sin(水平角), 负号修正方向

% 合并为3行矩阵 (每列一个点)
XYZ_Results = [xp; yp; zp];

fprintf('3D坐标计算完成: X范围[%.1f,%.1f], Y范围[%.1f,%.1f], Z范围[%.1f,%.1f]\n', ...
        min(xp), max(xp), min(yp), max(yp), min(zp), max(zp));

%% ===================== 5. 步骤4: 光谱强度与反射率 =====================
% ========================================================================
% 功能:
%   (1) 对6个波长通道分别检测峰值位置和幅度
%   (2) 计算基线偏移Y_Offset (脉冲左右基线的平均值)
%   (3) 真实脉冲幅度 = 峰值幅度 - 基线偏移
%   (4) 反射率 = 目标脉冲幅度 / 基准脉冲幅度 (白板标定)
%
% 脉冲峰值检测:
%   在互相关确定的峰值位置附近, 取SegmentCal_Width=60点窗口
%   找窗口内最大值作为该通道的峰值
%
% 基线计算:
%   在脉冲两侧各取EP_OffsetCal_scope/2=45点
%   左右基线均值作为直流偏置估计
%
% 反射率:
%   RFL(i) = (Y_peak_target - Y_offset) / Y_Amp_SWB(i)
%   其中Y_Amp_SWB是白板标定的参考幅度
% ========================================================================

fprintf('\n--- 步骤4: 光谱强度与反射率计算 ---\n');

% -------------------------------------------------------------------------
% 4.1 参数设置
% -------------------------------------------------------------------------
SegmentCal_Width = 60;      % 峰值检测窗口宽度, 单位采样点 (6ns)
EchoPulse_scope = 30;       % 脉冲范围, 用于基线计算 (3ns)
EP_OffsetCal_scope = 90;   % 基线计算范围, 脉冲两侧各45点 (4.5ns)

RFL = zeros(sample_num, 6);  % 6通道反射率矩阵

% -------------------------------------------------------------------------
% 4.2 主循环: 逐scan计算6通道反射率
% -------------------------------------------------------------------------
for j = 1:sample_num
    % 跳过无效数据 (互相关峰值位置异常)
    if Data_X_1stEchosPeak(j) > 1000 || Data_X_1stEchosPeak(j) < 100
        RFL(j, :) = 0;
        continue;
    end

    % 当前scan的滤波后信号
    signal_cal = Echo_cal(j, :);

    % -------------------------------------------------------------------------
    % 4.2.1 计算6个通道的峰值位置
    % -------------------------------------------------------------------------
    % 互相关峰值 + 模板偏移 = 各通道理论峰值位置
    X_EchosPeak = X_peaks_temp + Data_X_1stEchosPeak(j) - 1;

    % 峰值检测窗口边界
    Segment_Start = X_EchosPeak - round(0.5 * SegmentCal_Width);
    Segment_End = X_EchosPeak + round(0.5 * SegmentCal_Width);

    % 初始化
    X_peaks_Target = zeros(1, 6);
    Y_peaks_Target = zeros(1, 6);

    % 对6个通道分别找峰值
    for i = 1:6
        % 边界保护: 避免超出信号范围
        if Segment_End(i) < 1632
            % 正常情况: 取窗口内的信号段
            sub_arr = signal_cal(Segment_Start(i):Segment_End(i));
        else
            % 边界情况: 取信号末尾的固定宽度
            sub_arr = signal_cal(end - SegmentCal_Width:end);
        end

        % 找窗口内最大值及其位置
        [max_val, sub_max_idx] = max(sub_arr);

        % 计算实际峰值位置 = 窗口起始 + 峰值偏移 - 1
        X_peaks_Target(i) = Segment_Start(i) + sub_max_idx - 1;
        Y_peaks_Target(i) = max_val;
    end

    % -------------------------------------------------------------------------
    % 4.2.2 计算基线偏移 (直流偏置)
    % -------------------------------------------------------------------------
    % 脉冲有效范围
    EPS_Start = X_peaks_Target - round(0.5 * EchoPulse_scope);   % 脉冲起始
    EPS_End = X_peaks_Target + round(0.5 * EchoPulse_scope);     % 脉冲结束

    % 基线计算范围 (脉冲两侧)
    EPOC_Start = X_peaks_Target - round(0.5 * EP_OffsetCal_scope);  % 基线左界
    EPOC_End = X_peaks_Target + round(0.5 * EP_OffsetCal_scope);    % 基线右界

    % 计算每个通道的基线偏移
    Y_Offset_Target = zeros(1, 6);
    for i = 1:6
        % 取脉冲左侧基线区间
        sub_arr_left = signal_cal(EPOC_Start(i):EPS_Start(i));
        % 取脉冲右侧基线区间
        sub_arr_right = signal_cal(EPS_End(i):EPOC_End(i));
        % 左右基线均值作为直流偏置估计
        Y_Offset_Target(i) = 0.5 * (mean(sub_arr_left) + mean(sub_arr_right));
    end

    % -------------------------------------------------------------------------
    % 4.2.3 计算反射率
    % -------------------------------------------------------------------------
    % 真实脉冲幅度 = 峰值 - 基线
    Y_Amp_Target = Y_peaks_Target - Y_Offset_Target;

    % 反射率 = 目标幅度 / 基准幅度 (白板标定值)
    RFL(j, :) = Y_Amp_Target ./ Y_Amp_SWB;

    % 每1000个scan报告进度
    if mod(j, 1000) == 0
        fprintf('  已处理 %d / %d\n', j, sample_num);
    end
end

fprintf('光谱反射率计算完成\n');

%% ===================== 6. 步骤5: 彩色点云生成 =====================
% ========================================================================
% 功能:
%   (1) 读取CIE色彩匹配函数 (CMF)
%   (2) 将6通道光谱反射率转换为CIE XYZ色彩空间
%   (3) 将XYZ转换为RGB颜色 (考虑显示器特性)
%   (4) 生成彩色3D点云可视化
%
% 色彩转换原理:
%   CIE XYZ色彩空间是基于人眼视觉特性的标准色彩空间
%   CMF (Color Matching Function) 描述了各波长对人眼三种感光细胞的刺激程度
%
% XYZ计算:
%   X = sum(CMF_X(λi) × RFL(λi))  for i = 1 to 6
%   Y, Z 同理
%
% XYZ转RGB:
%   使用显示器磷光体特性矩阵tranRGB
%   [R, G, B]^T = inv(tranRGB) × [X, Y, Z]^T
% ========================================================================

fprintf('\n--- 步骤5: 彩色点云生成 ---\n');

% -------------------------------------------------------------------------
% 5.1 读取色彩匹配函数 (CMF)
% -------------------------------------------------------------------------
% cmf_path指向的.mat文件包含:
%   cmf(:,1) = x成分 (红感光细胞)
%   cmf(:,2) = y成分 (绿感光细胞)
%   cmf(:,3) = z成分 (蓝感光细胞)
% 文件格式: 481行 × 3列, 对应461nm-701nm (5nm间隔)
cmf = importdata(cmf_path);
xh = cmf(:, 1);
yh = cmf(:, 2);
zh = cmf(:, 3);

% -------------------------------------------------------------------------
% 5.2 XYZ转RGB转换矩阵
% -------------------------------------------------------------------------
% 这是将CIE XYZ色彩空间转换为显示器RGB的转换矩阵
% 矩阵元素由显示器磷光体特性决定 (sRGB标准)
tranRGB = [2.768892, 1.751748, 1.130160; ...  % X -> R,G,B 转换系数
           1.000000, 4.590700, 0.060100; ...
           0, 0.056508, 5.594292];

% -------------------------------------------------------------------------
% 5.3 插值获取6个波长对应的CMF值 (只需5个通道，跳过642nm)
% -------------------------------------------------------------------------
% 原代码只使用5个波长通道 (495,696,600,545,803nm)，跳过642nm
% 索引对应: lam6da(1)=495, lam6da(2)=696, lam6da(3)=600, lam6da(5)=545, lam6da(6)=642
idx6da_used = round(([lam6da(1), lam6da(2), lam6da(3), lam6da(5), lam6da(6)] - 461) / 5) + 1;

xh_vals = interp1(1:length(xh), xh, idx6da_used, 'linear');
yh_vals = interp1(1:length(yh), yh, idx6da_used, 'linear');
zh_vals = interp1(1:length(zh), zh, idx6da_used, 'linear');

% 归一化因子: Y分量之和的倒数 (只基于5个通道)
dk = 1 / sum(yh_vals);

% -------------------------------------------------------------------------
% 5.4 主循环: 光谱反射率 -> XYZ -> RGB
% -------------------------------------------------------------------------
C_X = zeros(1, sample_num);  % CIE X 刺激值
C_Y = zeros(1, sample_num);  % CIE Y 刺激值 (亮度)
C_Z = zeros(1, sample_num);  % CIE Z 刺激值
clb = zeros(sample_num, 3);  % RGB颜色矩阵

% 将RFL按列组织为 9000 x 6 矩阵, 便于逐点处理
Int_lamda = [RFL(:, 1), RFL(:, 2), RFL(:, 3), RFL(:, 4), RFL(:, 5), RFL(:, 6)];

for i = 1:sample_num
    % -----------------------------------------------------------------
    % 5.4.1 光谱加权求和得到XYZ (只使用5个通道，跳过642nm)
    % -----------------------------------------------------------------
    % zh_vals/yh_vals/xh_vals 索引: [1]=495nm, [2]=696nm, [3]=600nm, [4]=545nm, [5]=642nm
    % Int_lamda 列索引:        [1]=495nm, [2]=696nm, [3]=600nm, [5]=545nm, [6]=642nm
    % 映射关系: zh_vals(j) 对应 Int_lamda(:, col_j)，其中 col_j = [1, 2, 3, 5, 6]
    % 即: zh_vals(1)←Int_lamda(:,1), zh_vals(2)←Int_lamda(:,2), zh_vals(3)←Int_lamda(:,3),
    %     zh_vals(4)←Int_lamda(:,5), zh_vals(5)←Int_lamda(:,6)
    C_Z(i) = zh_vals(1) * Int_lamda(i, 1) + zh_vals(2) * Int_lamda(i, 2) + ...
             zh_vals(3) * Int_lamda(i, 3) + zh_vals(4) * Int_lamda(i, 5) + zh_vals(5) * Int_lamda(i, 6);
    C_Y(i) = yh_vals(1) * Int_lamda(i, 1) + yh_vals(2) * Int_lamda(i, 2) + ...
             yh_vals(3) * Int_lamda(i, 3) + yh_vals(4) * Int_lamda(i, 5) + yh_vals(5) * Int_lamda(i, 6);
    C_X(i) = xh_vals(1) * Int_lamda(i, 1) + xh_vals(2) * Int_lamda(i, 2) + ...
             xh_vals(3) * Int_lamda(i, 3) + xh_vals(4) * Int_lamda(i, 5) + xh_vals(5) * Int_lamda(i, 6);

    % -----------------------------------------------------------------
    % 5.4.2 XYZ归一化
    % -----------------------------------------------------------------
    C_X(i) = dk * C_X(i);
    C_Y(i) = dk * C_Y(i);
    C_Z(i) = dk * C_Z(i);

    % -----------------------------------------------------------------
    % 5.4.3 XYZ转RGB (求解线性方程组)
    % -----------------------------------------------------------------
    % tranRGB × [R;G;B] = [X;Y;Z]
    % 因此 [R;G;B] = inv(tranRGB) × [X;Y;Z]
    % MATLAB中 A\b 等效于 inv(A)*b
    vc = tranRGB \ [C_X(i); C_Y(i); C_Z(i)];

    % 负值设为0 (颜色不能为负)
    vc(vc < 0) = 0;

    % -----------------------------------------------------------------
    % 5.4.4 颜色增益调整
    % -----------------------------------------------------------------
    % 不同通道灵敏度不同, 乘以经验系数进行校正
    RGB_R = 0.89 * vc(1);   % 红通道增益
    RGB_G = 1.01 * vc(2);   % 绿通道增益
    RGB_B = 5.1 * vc(3);    % 蓝通道增益 (蓝通道灵敏度低, 增益较大)

    % -----------------------------------------------------------------
    % 5.4.5 颜色饱和度调整
    % -----------------------------------------------------------------
    % 整体亮度增强, 再裁剪到[0,1]范围
    clbt1 = [RGB_R, RGB_G, RGB_B];
    clbt = 4.5 * clbt1;          % 整体增益 (与a1.m一致)
    clbt(clbt > 1) = 1;          % 限幅

    % 保存RGB颜色
    clb(i, 1) = clbt(1);  % R
    clb(i, 2) = clbt(2);  % G
    clb(i, 3) = clbt(3);  % B
end

fprintf('颜色映射完成\n');

